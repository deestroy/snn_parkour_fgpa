# ---------------------------------------------------------------- quantisation per layer, per network on the board / in the ladder
def quantisation():
    nets = [("N-MNIST (seed 0, T=4)", "golden/m1_weights_int8.npz", sorted(glob.glob("experiments/*golden*seed0*.log")) or []),
            ("DVS-Gesture (seed 0, T=4)", "golden/dvsgesture_weights_int8.npz", sorted(glob.glob("experiments/dvsgesture/golden_check_seed0.log"))),
            ("robot student r1 (recreation)", "golden/r1_student_weights_int8.npz", [])]
    rows = []
    for name, npz, logs in nets:
        d = np.load(npz)
        rng = {}
        if logs:
            txt = open(logs[-1]).read()
            for m in re.finditer(r"(c1|c2|c3|fc)\s+V in \[\s*(-?\d+),\s*(-?\d+)\]", txt):
                lo, hi = int(m.group(2)), int(m.group(3)); rng[m.group(1)] = "%d..%d (%.0f %% of int16)" % (lo, hi, 100 * max(hi / 32767, -lo / 32768))
        for layer, key in (("C1", "conv1"), ("C2", "conv2"), ("C3", "conv3"), ("FC", "fc")):
            if key not in d.files:
                continue
            k = int(d[key + "_k"]); w = d[key]
            clip = float(d[key + "_clip_frac"]) if key + "_clip_frac" in d.files else 0.0
            rows.append((name, layer, "x".join(str(x) for x in w.shape), k, "2^-%d" % k, 2 ** k, "%.3f %%" % (100 * clip), int(np.abs(w).max()), rng.get(key.replace("conv", "c"), "--")))
    open(os.path.join(OUT, "quantisation.md"), "w").write(
        "# Quantisation per layer\n\nGenerated by make_tables.py from the tracked int8 weight files (golden/*.npz: shift k per layer, threshold 2^k, clip fraction) and the golden-check logs where present (membrane range over the check run). Weights are int8 at scale 2^-k; the integer threshold equals 2^k so a unit float threshold maps to the same scale; the FC folds the 2x2 pool's /4 into k+2 (D0004, D0008).\n\n"
        + md_table(["network", "layer", "weight shape", "k", "scale", "threshold", "clipped weights", "max |int8|", "membrane range (golden check)"], rows))
    return len(rows)


