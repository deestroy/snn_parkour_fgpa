# ---------------------------------------------------------------- quantisation per layer, per network on the board / in the ladder
def quantisation():
    nets = [("N-MNIST (seed 0, T=4)", "golden/m1_weights_int8.npz", sorted(glob.glob("experiments/*golden*seed0*.log")) or []),
            ("DVS-Gesture (seed 0, T=4)", "golden/dvsgesture_weights_int8.npz", sorted(glob.glob("experiments/dvsgesture/golden_check_seed0.log"))),
            ("robot student r1 (recreation)", "golden/r1_student_weights_int8.npz", [])]
    rows = []
    for name, npz, logs in nets:
        d = np.load(npz)
        rng = {}
        if logs:
            txt = open(logs[-1]).read()
            for m in re.finditer(r"(c1|c2|c3|fc)\s+V in \[\s*(-?\d+),\s*(-?\d+)\]", txt):
                lo, hi = int(m.group(2)), int(m.group(3)); rng[m.group(1)] = "%d..%d (%.0f %% of int16)" % (lo, hi, 100 * max(hi / 32767, -lo / 32768))
        for layer, key in (("C1", "conv1"), ("C2", "conv2"), ("C3", "conv3"), ("FC", "fc")):
            if key not in d.files:
                continue
            k = int(d[key + "_k"]); w = d[key]
            clip = float(d[key + "_clip_frac"]) if key + "_clip_frac" in d.files else 0.0
            rows.append((name, layer, "x".join(str(x) for x in w.shape), k, "2^-%d" % k, 2 ** k, "%.3f %%" % (100 * clip), int(np.abs(w).max()), rng.get(key.replace("conv", "c"), "--")))
    open(os.path.join(OUT, "quantisation.md"), "w").write(
        "# Quantisation per layer\n\nGenerated by make_tables.py from the tracked int8 weight files (golden/*.npz: shift k per layer, threshold 2^k, clip fraction) and the golden-check logs where present (membrane range over the check run). Weights are int8 at scale 2^-k; the integer threshold equals 2^k so a unit float threshold maps to the same scale; the FC folds the 2x2 pool's /4 into k+2 (D0004, D0008).\n\n"
        + md_table(["network", "layer", "weight shape", "k", "scale", "threshold", "clipped weights", "max |int8|", "membrane range (golden check)"], rows))
    return len(rows)


# ---------------------------------------------------------------- accuracy and firing rates per trained network
def _train_final(path):
    """(test acc, {c1,c2,c3,fc}) from a train log's last epoch line or a firing-rate CSV's last test row."""
    if path.endswith(".csv"):
        rows = [l.strip().split(",") for l in open(path) if l.strip() and not l.startswith("epoch")]
        r = [x for x in rows if x[1] == "test"][-1]
        return float(r[3]), dict(zip(("c1", "c2", "c3", "fc"), map(float, r[4:8])))
    last = None
    for l in open(path):
        m = re.match(r"epoch\s+(\d+).*test acc ([\d.]+).*c1=([\d.]+)\s+c2=([\d.]+)\s+c3=([\d.]+)\s+fc=([\d.]+)", l)
        if m:
            last = m
    return (float(last.group(2)), dict(zip(("c1", "c2", "c3", "fc"), map(float, last.groups()[2:])))) if last else (None, {})


def _golden(path):
    txt = open(path).read()
    f = re.search(r"float model\s*:\s*([\d.]+)%", txt); g = re.search(r"golden integer:\s*([\d.]+)%", txt)
    m = re.search(r"fc\s+V in \[\s*(-?\d+),\s*(-?\d+)\]", txt)
    pct = 100 * max(int(m.group(2)) / 32767, -int(m.group(1)) / 32768) if m else None
    return (float(f.group(1)) if f else None, float(g.group(1)) if g else None, pct)


def accuracy_rates():
    nets = []  # (dataset, network, seed, T, train source, golden log)
    nets.append(("N-MNIST", "baseline", 0, 4, "experiments/m0_firing_rates_binarised.csv", None))
    for T in (8, 16):
        for sd in (0, 1, 2):
            nets.append(("N-MNIST", "baseline", sd, T, "experiments/tsweep_nmnist/m0_firing_rates_binarised_nmnist_seed%d_t%d.csv" % (sd, T), "experiments/tsweep_nmnist/golden_t%d_seed%d.log" % (T, sd)))
    for r in ("0.02", "0.04", "0.08", "0.16", "0.30"):
        for sd in (0, 1, 2):
            sfx = "" if sd == 0 else "_seed%d" % sd
            nets.append(("N-MNIST", "rate target %s" % r, sd, 4, "experiments/rate_sweep/train_rate%s%s.log" % (r, sfx), "experiments/rate_sweep/golden_rate%s%s.log" % (r, sfx)))
            nets.append(("DVS-Gesture", "rate target %s" % r, sd, 4, "experiments/rate_sweep_dvsg/train_rate%s%s.log" % (r, sfx), "experiments/rate_sweep_dvsg/golden_rate%s%s.log" % (r, sfx)))
    for sd in (0, 1, 2):
        nets.append(("DVS-Gesture", "baseline", sd, 4, "experiments/dvsgesture/train_seed%d.log" % sd, "experiments/dvsgesture/golden_check_seed%d.log" % sd))
        for T in (8, 16):
            nets.append(("DVS-Gesture", "baseline", sd, T, "experiments/dvsgesture/t%d/train_seed%d.log" % (T, sd), "experiments/dvsgesture/t%d/golden_check_seed%d.log" % (T, sd)))
    rows = []
    for ds, net, sd, T, tr, gl in nets:
        if not os.path.exists(tr):
            continue
        acc, rates = _train_final(tr)
        fa, ga, pct = _golden(gl) if gl and os.path.exists(gl) else (None, None, None)
        fmt = lambda v: "--" if v is None else "%.2f" % v
        rows.append((ds, net, sd, T, fmt(100 * acc if acc is not None else None), fmt(ga), "--" if pct is None else ("%.0f %%" % pct + (" **overflow**" if pct > 100 else "")),
                     "%.3f / %.3f / %.3f / %.3f" % (rates["c1"], rates["c2"], rates["c3"], rates["fc"]) if rates else "--", os.path.relpath(tr)))
    rows.sort(key=lambda r: (r[0], r[1] != "baseline", r[1], r[3], r[2]))
    open(os.path.join(OUT, "accuracy_rates.md"), "w").write(
        "# Accuracy and firing rates per trained network\n\nGenerated by make_tables.py from the training logs / firing-rate CSVs (final-epoch test accuracy and per-layer test firing rates) and the golden-check logs (integer-model accuracy on the full test set; fc membrane use as % of int16). Rates are the fraction of neurons firing per timestep on the test set. A row without a golden column has no golden log in the repository.\n\n"
        + md_table(["dataset", "network", "seed", "T", "float test acc (%)", "golden integer acc (%)", "fc membrane (% of int16)", "rates c1 / c2 / c3 / fc", "source"], rows))
    return len(rows)


# ---------------------------------------------------------------- T sweep summary
def tsweep():
    groups = [("N-MNIST", 4, ["experiments/m0_firing_rates_binarised.csv"], []),
              ("N-MNIST", 8, [], glob.glob("experiments/tsweep_nmnist/golden_t8_seed*.log")),
              ("N-MNIST", 16, [], glob.glob("experiments/tsweep_nmnist/golden_t16_seed*.log")),
              ("DVS-Gesture", 4, [], glob.glob("experiments/dvsgesture/golden_check_seed*.log")),
              ("DVS-Gesture", 8, [], glob.glob("experiments/dvsgesture/t8/golden_check_seed*.log")),
              ("DVS-Gesture", 16, [], glob.glob("experiments/dvsgesture/t16/golden_check_seed*.log"))]
    rows = []
    for ds, T, csvs, logs in groups:
        fl, gl, pc = [], [], []
        for f in logs:
            a, b, c = _golden(f); fl.append(a); gl.append(b); pc.append(c)
        for f in csvs:
            fl.append(100 * _train_final(f)[0])
        ms = lambda v: "--" if not v else ("%.2f" % v[0] if len(v) == 1 else "%.2f +- %.2f" % (np.mean(v), np.std(v, ddof=1)))
        rows.append((ds, T, len(fl), ms([x for x in fl if x is not None]), ms([x for x in gl if x is not None]),
                     "--" if not pc else "%.0f-%.0f %%" % (min(pc), max(pc)), "--" if not pc else "%d of %d" % (sum(1 for x in pc if x > 100), len(pc))))
    open(os.path.join(OUT, "tsweep.md"), "w").write(
        "# Timesteps T vs accuracy and the int16 membrane ceiling\n\nGenerated by make_tables.py from the golden-check logs per (dataset, T, seed). Accuracy mean +- sd over seeds (sample sd); fc membrane use = peak |V| as a fraction of int16 over the golden run; a network 'overflows' when that exceeds 100 %% (the hardware membrane is int16, the golden model's is int32 -- see C0046). N-MNIST T=4 has no golden log with a membrane line in the repository; its float accuracy comes from the M0 CSV.\n\n"
        + md_table(["dataset", "T", "seeds", "float acc (%)", "golden integer acc (%)", "fc membrane (% of int16, min-max)", "overflowing seeds"], rows))
    return len(rows)


# ---------------------------------------------------------------- crossover table: every axis, layer, dataset, basis
def crossover():
    rows = []
    # parallelism axis, C1: fit ED(K) = a + b/K over K=1..16 and dense(P) = c/P (+ measured P=4 point), solve ED = dense
    for ds, d, extra in (("N-MNIST", "experiments/latency_sim/ksweep_c0035", {4: 104059}), ("DVS-Gesture", "experiments/dvsgesture/latency_sim", {})):
        Ks = [1, 2, 4, 8, 16]; ed = [cycles_file(os.path.join(d, "ed_k%d.txt" % k)).mean() for k in Ks]
        A = np.vstack([np.ones(5), 1.0 / np.array(Ks)]).T; a, b = np.linalg.lstsq(A, np.array(ed), rcond=None)[0]
        dn = dict(extra)
        for P in Ks:
            f = os.path.join(d, "dense_p%d.txt" % P)
            if os.path.exists(f):
                dn[P] = dense_cycles(f)
        Ps = sorted(dn); B = np.vstack([1.0 / np.array(Ps), np.ones(len(Ps))]).T; c, dd = np.linalg.lstsq(B, np.array([dn[p] for p in Ps]), rcond=None)[0]
        kk = np.linspace(1, 32, 3101); x = kk[np.argmin(np.abs((a + b / kk) - (c / kk + dd)))]
        rows.append(("parallelism (K = P)", "C1", ds, "--", "K = P = %.1f" % x, "sim (cycle-model fits: ED over K = 1..16, dense over the P points in the files)", "silicon: ED wins at 4, dense at 8 (N-MNIST)" if ds == "N-MNIST" else "silicon: ED wins 6/8 clips at K = P = 4", "ED = %.0f + %.0f/K; dense = %.0f/P + %.0f" % (a, b, c, dd)))
    # activity axis, C1 per clip (DVS-Gesture): threshold in input spikes from the README statement
    txt = open("experiments/dvsgesture/latency_sim/README.md").read()
    m = re.search(r"fewer than ~([\d,]+) spikes", txt)
    rows.append(("activity (per sample)", "C1", "DVS-Gesture", "K = P = 4", "< ~%s input spikes per inference (~30.5 %% density)" % (m.group(1) if m else "10,000"), "sim, pre-registered", "silicon: ED wins 6/8 clips, loses clips 1 and 5 (36 %, 44 %)", "clip densities 9-44 %"))
    # activity axis by training, C2/C3, from the per-K fits
    cfg = [("N-MNIST", "experiments/rate_sweep", "golden/traces_m1.npz", {"c2": ("c1_S", 16 * 17 * 17, "C2"), "c3": ("c2_S", 32 * 9 * 9, "C3")}),
           ("DVS-Gesture", "experiments/rate_sweep_dvsg", "golden/traces_dvsgesture.npz", {"g2": ("c1_S", 16 * 32 * 32, "C2"), "g3": ("c2_S", 32 * 16 * 16, "C3")})]
    tags = ["base", "0.02", "0.04", "0.08", "0.16", "0.30"]
    for ds, d, base_tr, layers in cfg:
        for L, (key, inbits, name) in layers.items():
            base_rate = None
            for K in (4, 8, 16):
                xs, ys = [], []
                for t in tags:
                    f = os.path.join(d, "bench", "ed_k%d_%s_%s.txt" % (K, t, L)); tr = base_tr if t == "base" else os.path.join(d, "traces_rate%s.npz" % t)
                    if os.path.exists(f) and os.path.exists(tr) and len(cycles_file(f)):
                        sp = int((np.load(tr)[key] != 0).sum()) / 16; xs.append(sp); ys.append(cycles_file(f).mean())
                        if t == "base": base_rate = 100 * sp / (4 * inbits)
                if len(xs) < 3:
                    continue
                A = np.vstack([np.ones(len(xs)), xs]).T; a, b = np.linalg.lstsq(A, np.array(ys), rcond=None)[0]
                dn = dense_cycles(os.path.join(d, "bench", "dense_p4_base_%s.txt" % L)) / (K / 4)
                cx = 100 * ((dn - a) / b) / (4 * inbits)
                rows.append(("activity (trained)", name, ds, "K = P = %d" % K, "%.0f %% input activity" % cx, "sim (6 networks, 16 samples each, fit ED = a + b s)",
                             "baseline network at %.1f %%: %s" % (base_rate, "ED wins" if base_rate < cx else "dense wins"), "a = %.0f, b = %.1f cycles/spike" % (a, b)))
    open(os.path.join(OUT, "crossover.md"), "w").write(
        "# Crossover table: every axis, layer and dataset\n\nGenerated by make_tables.py from experiments/latency_sim, experiments/dvsgesture/latency_sim and the rate-sweep bench files. 'Basis' says whether the number is a simulation fit or a silicon observation; the silicon column states what the board showed at the bracketing points. The operating point is the unregularised (baseline) network's input activity on the check set.\n\n"
        + md_table(["axis", "layer", "dataset", "at", "crossover", "basis", "operating point / silicon", "fit"], rows))
    return len(rows)


