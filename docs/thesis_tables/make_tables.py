def deadline():
    sets = []
    f64 = "experiments/p1_distill/isaac_i1_ed_k4_cycles_64.txt"
    if os.path.exists(f64) and len(cycles_file(f64)):
        sets.append(("robot event frames (64, sim)", cycles_file(f64) / 100.0, 1441788 / 4 / 100.0))
    k8, k4 = [], []
    for l in open("experiments/board_ed_k8_20260917.md"):
        m = re.match(r"\| (\d+) \| \d \| ([\d.]+) \| ([\d.]+) \| \+[\d.]+ % \| ([\d.]+) \|", l)
        if m:
            k8.append(float(m.group(2))); k4.append(float(m.group(4)))
    sets.append(("N-MNIST C1 (16 samples, board, K = P = 4)", np.array(k4), 1048.9))
    sets.append(("N-MNIST C1 (16 samples, board, K = P = 8)", np.array(k8), 540.3))
    db = []
    for l in open("experiments/dvsgesture/board_ed_k4_20260919.md"):
        m = re.match(r"\| (\d) \| \d+ \| ([\d.]+) \| ([\d.]+) \|", l)
        if m:
            db.append(float(m.group(2)))
    sets.append(("DVS-Gesture C1 (8 clips, board, K = P = 4)", np.array(db), 3706.5))
    rows = []
    for name, ed, dn in sets:
        miss = lambda hz, arr: 100 * np.mean(arr > 1e6 / hz)
        rows.append((name, "ED", "%.0f" % ed.mean(), "%.0f" % ed.max(), "%.2fx" % (ed.max() / ed.min()), "%.1f %%" % (100 * ed.max() / 1e5), "%.0f Hz" % (1e6 / ed.max()),
                     " / ".join("%.0f" % miss(hz, ed) for hz in (10, 20, 50, 100, 200))))
        rows.append((name, "dense", "%.0f" % dn, "%.0f" % dn, "1.00x", "%.1f %%" % (100 * dn / 1e5), "%.0f Hz" % (1e6 / dn),
                     " / ".join("%.0f" % (100.0 if dn > 1e6 / hz else 0.0) for hz in (10, 20, 50, 100, 200))))
    open(os.path.join(OUT, "deadline.md"), "w").write(
        "# Deadline reading: per-sample latency distributions against perception periods\n\nGenerated by make_tables.py from the per-sample cycle/board files. 'Max sustainable rate' is the perception rate at which the WORST sample still meets its period (1 / worst latency, engine-only, no host or DMA time); miss rate at a given rate is the fraction of samples whose latency exceeds that period. The robot's control period is 100 ms (10 Hz), so the budget fraction column is worst latency / 100 ms. Both engines meet every period up to 200 Hz on every set; the difference between them appears only above that, and in the spread.\n\n"
        + md_table(["sample set", "engine", "mean (us)", "worst (us)", "spread max/min", "worst as % of 100 ms budget", "max sustainable rate", "miss rate % at 10 / 20 / 50 / 100 / 200 Hz"], rows))
    return len(rows)


